#!/usr/bin/env python3
"""Local Kirchenbauer green-list watermark detector (CPU, no API).

Gives Layer B a number instead of a promise. Scores text against the
green-list scheme from Kirchenbauer et al., *A Watermark for Large Language
Models* (arXiv:2301.10226): each token's predecessor seeds a pseudorandom
split of the vocabulary into a "green" fraction gamma, and watermarked
generation biases sampling toward green tokens. Counting green hits over a
document gives a z-score against the unwatermarked null of gamma.

Run it before and after a rewrite to see the signal fall.

SCOPE — what this can and cannot do:

  CAN detect: text generated by an open model using the standard Kirchenbauer
  scheme with a key you know (the default is the reference implementation's).
  This is the "Open-LLM" column of the project's coverage matrix.

  CANNOT detect: Claude, Gemini/SynthID-Text, or OpenAI marks. Those use
  secret keys and undisclosed schemes; without the key the green list is
  unknowable and this tool will correctly report ~0 for watermarked text.
  A low score here is NOT evidence that a vendor detector will fail.

Exit codes:
  0  scored successfully
  1  runtime error
  2  bad input
  3  unavailable (no tokenizer, or numpy missing)
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Sequence

SCRIPTS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS_DIR))

from common import emit_json, eprint, read_text_input  # noqa: E402

try:
    import numpy as np
except ImportError:  # pragma: no cover - exercised via the CLI exit code
    eprint("detect_text_watermark needs numpy: pip install numpy")
    raise SystemExit(3) from None

# Reference implementation defaults (lm-watermarking). Different values are a
# different watermark: detection only works when they match generation.
DEFAULT_GAMMA = 0.25
DEFAULT_HASH_KEY = 15485863

# Conventional detection threshold. z=4 is ~3e-5 false-positive rate one-sided,
# which the paper uses as its operating point.
DEFAULT_Z_THRESHOLD = 4.0

# Below this many scored tokens the estimator is too noisy to claim anything.
MIN_TOKENS_FOR_A_CLAIM = 50

SCOPE_NOTE = (
    "Detects the standard Kirchenbauer green-list scheme with a known key "
    "(open-LLM class). It cannot detect Claude, Gemini/SynthID-Text or OpenAI "
    "marks, which use secret keys and undisclosed schemes — a low score here is "
    "not evidence that a vendor detector would fail."
)


def z_score(green: int, total: int, gamma: float) -> float:
    """Standardized deviation of the green-token count from its null mean.

    Under no watermark each token is green with probability gamma, so the count
    is Binomial(total, gamma): mean gamma*T, variance gamma*(1-gamma)*T.
    """
    if not 0.0 < gamma < 1.0:
        raise ValueError(f"gamma must be in (0, 1), got {gamma}")
    if total <= 0:
        return 0.0
    expected = gamma * total
    stdev = math.sqrt(total * gamma * (1.0 - gamma))
    if stdev == 0:
        return 0.0
    return (green - expected) / stdev


def green_ids(prev_id: int, vocab_size: int, gamma: float, hash_key: int) -> "np.ndarray":
    """The green-list token ids for a given preceding token.

    Seeding a permutation with hash_key * prev_id and taking the first
    gamma*V entries reproduces the reference scheme's "lefthash" partition.
    """
    if vocab_size <= 0:
        raise ValueError(f"vocab_size must be positive, got {vocab_size}")
    if not 0.0 < gamma < 1.0:
        raise ValueError(f"gamma must be in (0, 1), got {gamma}")
    size = int(vocab_size * gamma)
    rng = np.random.default_rng((hash_key * (prev_id + 1)) % (2**63 - 1))
    return rng.permutation(vocab_size)[:size]


def score_tokens(
    token_ids: Sequence[int],
    *,
    vocab_size: int,
    gamma: float = DEFAULT_GAMMA,
    hash_key: int = DEFAULT_HASH_KEY,
    z_threshold: float = DEFAULT_Z_THRESHOLD,
) -> dict[str, Any]:
    """Score a token sequence for green-list bias.

    The first token has no predecessor and is not scored. Green lists are
    cached per preceding token id: real text reuses prefixes heavily, so this
    turns an O(V) permutation per token into one per *distinct* prefix.
    """
    ids = [int(t) for t in token_ids]
    green_count = 0
    scored = 0
    cache: dict[int, set[int]] = {}

    for prev, cur in zip(ids, ids[1:]):
        members = cache.get(prev)
        if members is None:
            members = set(int(x) for x in green_ids(prev, vocab_size, gamma, hash_key))
            cache[prev] = members
        scored += 1
        if cur in members:
            green_count += 1

    z = z_score(green_count, scored, gamma)
    inconclusive = scored < MIN_TOKENS_FOR_A_CLAIM
    return {
        "tokens_total": len(ids),
        "tokens_scored": scored,
        "green_tokens": green_count,
        "green_rate": (green_count / scored) if scored else 0.0,
        "expected_rate": gamma,
        "z_score": round(z, 4),
        "z_threshold": z_threshold,
        "p_value": round(0.5 * math.erfc(z / math.sqrt(2)), 8) if scored else 1.0,
        "watermark_detected": bool(z > z_threshold and not inconclusive),
        "inconclusive": inconclusive,
        "vocab_size": vocab_size,
        "gamma": gamma,
        "hash_key": hash_key,
        "scope": SCOPE_NOTE,
    }


# --- tokenization ---------------------------------------------------------


def _tokenize_transformers(text: str, name: str) -> tuple[list[int], int] | None:
    """Tokenize with a local HF tokenizer, if transformers is installed."""
    try:
        from transformers import AutoTokenizer
    except ImportError:
        return None
    try:
        tok = AutoTokenizer.from_pretrained(name)
        ids = tok(text, add_special_tokens=False)["input_ids"]
        return list(ids), int(tok.vocab_size)
    except Exception as e:
        eprint(f"tokenizer '{name}' unavailable: {e}")
        return None


def _tokenize_llamacpp(text: str, base_url: str, timeout: float = 10.0):
    """Tokenize via a running llama-server, so no extra install is needed."""
    url = base_url.rstrip("/") + "/tokenize"
    body = json.dumps({"content": text}).encode("utf-8")
    req = urllib.request.Request(
        url, data=body, headers={"Content-Type": "application/json"}, method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, OSError, ValueError):
        return None
    ids = data.get("tokens")
    if not ids:
        return None
    return [int(t) for t in ids], None


def main() -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("path", help="Text file to score, or - for stdin")
    p.add_argument(
        "--token-ids",
        action="store_true",
        help="Input is a JSON array of token ids, not text (skips tokenization)",
    )
    p.add_argument(
        "--tokenizer",
        default="gpt2",
        help="HF tokenizer name for local tokenization (default: gpt2)",
    )
    p.add_argument(
        "--llamacpp-url",
        default="http://127.0.0.1:8080",
        help="llama-server used to tokenize when transformers is unavailable",
    )
    p.add_argument("--vocab-size", type=int, default=None, help="Override vocabulary size")
    p.add_argument("--gamma", type=float, default=DEFAULT_GAMMA)
    p.add_argument("--hash-key", type=int, default=DEFAULT_HASH_KEY)
    p.add_argument("--z-threshold", type=float, default=DEFAULT_Z_THRESHOLD)
    p.add_argument("--json", action="store_true", help="Emit JSON on stdout")
    args = p.parse_args()

    if args.path != "-" and not Path(args.path).is_file():
        eprint(f"not a file: {args.path}")
        return 2

    raw = read_text_input(args.path)

    if args.token_ids:
        try:
            ids = [int(t) for t in json.loads(raw)]
        except (json.JSONDecodeError, TypeError, ValueError) as e:
            eprint(f"could not parse token ids: {e}")
            return 2
        vocab = args.vocab_size
        if not vocab:
            eprint("--vocab-size is required with --token-ids")
            return 2
    else:
        result = _tokenize_transformers(raw, args.tokenizer)
        vocab_from_tokenizer = None
        if result is None:
            result = _tokenize_llamacpp(raw, args.llamacpp_url)
            if result is None:
                eprint(
                    "no tokenizer available. Install transformers "
                    "(pip install transformers), start a llama-server, or pass "
                    "--token-ids with pre-tokenized input."
                )
                return 3
            ids, vocab_from_tokenizer = result
        else:
            ids, vocab_from_tokenizer = result
        vocab = args.vocab_size or vocab_from_tokenizer
        if not vocab:
            eprint("could not determine vocabulary size; pass --vocab-size")
            return 3

    try:
        report = score_tokens(
            ids,
            vocab_size=vocab,
            gamma=args.gamma,
            hash_key=args.hash_key,
            z_threshold=args.z_threshold,
        )
    except ValueError as e:
        eprint(f"error: {e}")
        return 2

    if args.json:
        emit_json(report)
    else:
        verdict = "DETECTED" if report["watermark_detected"] else "not detected"
        if report["inconclusive"]:
            verdict = "inconclusive (too few tokens)"
        print(f"Kirchenbauer green-list watermark: {verdict}")
        print(
            f"  z = {report['z_score']:.3f} (threshold {report['z_threshold']}), "
            f"p = {report['p_value']:.2e}"
        )
        print(
            f"  green {report['green_tokens']}/{report['tokens_scored']} "
            f"= {report['green_rate']:.3f} (expected {report['expected_rate']:.3f})"
        )
        print(f"  scope: {SCOPE_NOTE}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
